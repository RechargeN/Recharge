/**
 * The public code of the content_result schema (`validationViolation`):
 * snake_case segments without a suffix. Internal Place codes are camelCase
 * (`place.pricing.entryType` → `place.pricing.entry_type`); a fixed suffix is
 * dropped (`place.hours.mode_unsupported:seasonal` → `place.hours.mode_unsupported`).
 */
export function publicCode(code: string): string {
  const base = code.includes(':') ? code.slice(0, code.indexOf(':')) : code;
  return base.replace(/[A-Z]/gu, (letter) => `_${letter.toLowerCase()}`);
}

/** Server registry criterion ids (never caller keys) are public. */
const criterionId = /^[a-z][a-z0-9_]{0,63}$/u;

export function publicValidationDetails(
  issues: readonly string[],
): readonly ContentValidationViolationV1[] {
  const details = new Map<string, ContentValidationViolationV1>();
  for (const issue of issues) {
    let code = issue;
    let fieldPath = Object.hasOwn(exactFields, issue) ? exactFields[issue] : undefined;
    if (issue.startsWith('activity.criterion_required:')) {
      const field = issue.slice('activity.criterion_required:'.length);
      if (publicCriteria.has(field)) {
        code = 'activity.criterion_required';
        fieldPath = `/body/criteria/${field}`;
      }
    }
    if (issue.startsWith('place.criteria.required_missing:')) {
      const field = issue.slice('place.criteria.required_missing:'.length);
      if (criterionId.test(field)) {
        code = 'place.criteria.required_missing';
        fieldPath = `/body/criteria/${field}`;
      }
    }
    if (issue.startsWith('rental.private_field_forbidden:')) {
      code = 'rental.private_field_forbidden';
      fieldPath = '/body';
    }
    if (fieldPath !== undefined && details.size < 50) {
      code = publicCode(code);
      details.set(`${code}:${fieldPath}`, { code, fieldPath });
    }
  }
  return Object.freeze([...details.values()].map((item) => Object.freeze(item)));
}
